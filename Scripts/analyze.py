# PLOT 1 — Serial Algorithm Comparison
# ============================================================
def plot_serial_comparison(df):
    print("\n[Plot 1] Serial Algorithm Comparison")

    serial_configs = ["Serial", "Serial-MRV", "BranchBound", "BranchBoundMRV"]
    present = [c for c in serial_configs if c in df["Config"].unique()]
    if not present:
        print("  Skipped — no serial data found.")
        return

    avg = (
        df[df["Config"].isin(present)]
        .groupby(["Difficulty", "Config"])["Time_s"]
        .mean()
        .reset_index()
    )

    x     = np.arange(len(DIFFICULTIES))
    n     = len(present)
    width = 0.8 / n

    fig, ax = plt.subplots(figsize=(11, 5))

    for i, cfg in enumerate(present):
        vals = (
            avg[avg["Config"] == cfg]
            .set_index("Difficulty")
            .reindex(DIFFICULTIES)["Time_s"]
            .values
        )
        offset = (i - n / 2 + 0.5) * width
        ax.bar(x + offset, vals, width * 0.9,
               label=cfg, color=CONFIG_COLORS.get(cfg, "#888888"))

    ax.set_xlabel("Difficulty")
    ax.set_ylabel("Average Solve Time (seconds, log scale)")
    ax.set_title("Serial Algorithm Comparison\n"
                 "Serial  |  Serial-MRV  |  Branch & Bound  |  Branch & Bound MRV")
    ax.set_xticks(x)
    ax.set_xticklabels(DIFFICULTIES)
    ax.set_yscale("log")
    ax.legend()
    ax.grid(True, alpha=0.3, axis="y")

    fig.tight_layout()
    path = os.path.join(PLOT_DIR, "serial_comparison.png")
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {path}")


