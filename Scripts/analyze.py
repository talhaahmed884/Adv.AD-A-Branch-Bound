def config_label(row):
    alg = row["Algorithm"]
    if alg == "Serial":
        return "Serial"
    elif alg == "Serial-MRV":
        return "Serial-MRV"
    elif alg == "BranchBound":
        return "BranchBound"
    elif alg == "BranchBoundMRV":
        return "BranchBoundMRV"
    elif alg == "OpenMP":
        return f"OpenMP-{int(row['Threads'])}"
    else:  # OMP-BranchBoundMRV
        return f"OMP-BBMRV-{int(row['Threads'])}"


def load_data(paths):
    raw = pd.concat([pd.read_csv(p) for p in paths], ignore_index=True)
    raw = raw[raw["Time_s"] > 0].copy()
    print(f"Loaded {len(raw)} raw timing rows from {len(paths)} file(s).")

    group_keys = ["Board_ID", "Difficulty", "Algorithm", "Threads"]
    time_agg = (
        raw.groupby(group_keys)["Time_s"]
        .agg(Time_s="median", Time_min="min", Time_max="max", Time_std="std")
        .reset_index()
    )
    correct_agg = raw.groupby(group_keys)["Correct"].max().reset_index()

    has_nodes = "Nodes" in raw.columns
    if has_nodes:
        nodes_agg = (
            raw.groupby(group_keys)["Nodes"]
            .agg(Nodes="median", Nodes_min="min", Nodes_max="max")
            .reset_index()
        )

    df = time_agg.merge(correct_agg, on=group_keys)
    if has_nodes:
        df = df.merge(nodes_agg, on=group_keys)
    else:
        df["Nodes"] = pd.NA

    df["Config"] = df.apply(config_label, axis=1)
    df["Cost"]   = df["Threads"] * df["Time_s"]

    print(f"  Aggregated to {len(df)} config rows (median across reps).")
    return df


def compute_speedup(df):
    """
    Two parallel families — each measured against its own serial counterpart:
      OpenMP     — vs Serial-MRV baseline  (parallelism gain; same MRV algorithm, serial vs parallel)
      OMP-BBMRV  — vs BranchBoundMRV baseline (parallelism gain; same MRV+FC algorithm, serial vs parallel)
    """
    results = []

    def _merge(parallel_alg, baseline_alg, family_name):
        baseline = (
            df[df["Algorithm"] == baseline_alg][["Board_ID", "Difficulty", "Time_s"]]
            .rename(columns={"Time_s": "T_serial"})
        )
        parallel = df[df["Algorithm"] == parallel_alg].copy()
        if parallel.empty or baseline.empty:
            return
        merged = parallel.merge(baseline, on=["Board_ID", "Difficulty"])
        merged["Speedup"]    = merged["T_serial"] / merged["Time_s"]
        merged["Efficiency"] = merged["Speedup"] / merged["Threads"]
        merged["Family"]     = family_name
        results.append(merged)

    _merge("OpenMP",             "Serial-MRV",     "OpenMP")
    _merge("OMP-BranchBoundMRV", "BranchBoundMRV", "OMP-BBMRV")

    return pd.concat(results, ignore_index=True) if results else pd.DataFrame()


def compute_bound_effect(df):
    """
    Three pairwise comparisons that isolate the effect of adding the bounding function,
    holding everything else (cell selection strategy, parallelism) constant:

      NoMRV    — Serial        vs BranchBound         (row-major order; plain constraint check added)
      MRV      — Serial-MRV    vs BranchBoundMRV       (MRV order; forward checking added)
      Parallel — OpenMP        vs OMP-BranchBoundMRV   (parallel MRV; forward checking added, same threads)
    """
    results = []

    pairs = [
        ("Serial",     "BranchBound",       "NoMRV",    False),
        ("Serial-MRV", "BranchBoundMRV",    "MRV",      False),
        ("OpenMP",     "OMP-BranchBoundMRV", "Parallel", True),
    ]

    for base_alg, bb_alg, family, match_threads in pairs:
        keys = ["Board_ID", "Difficulty"] + (["Threads"] if match_threads else [])

        base = (
            df[df["Algorithm"] == base_alg][keys + ["Time_s"]]
            .rename(columns={"Time_s": "T_base"})
        )
        bb = (
            df[df["Algorithm"] == bb_alg][keys + ["Time_s"]]
            .rename(columns={"Time_s": "T_bb"})
        )

        if base.empty or bb.empty:
            continue

        merged = base.merge(bb, on=keys)
        merged["Family"] = family
        results.append(merged)

    return pd.concat(results, ignore_index=True) if results else pd.DataFrame()


def _aggregate_speedup(speedup_df, family=None):
    """Aggregate speedup: Σ T_baseline / Σ T_parallel per (Difficulty, Threads)."""
    subset = speedup_df if family is None else speedup_df[speedup_df["Family"] == family]
    rows = []
    for (diff, threads), g in subset.groupby(["Difficulty", "Threads"]):
        agg_speedup = g["T_serial"].sum() / g["Time_s"].sum()
        rows.append({
            "Difficulty":     diff,
            "Threads":        threads,
            "agg_speedup":    agg_speedup,
            "agg_efficiency": agg_speedup / threads,
            "lo":             g["Speedup"].quantile(0.25),
            "hi":             g["Speedup"].quantile(0.75),
        })
    return pd.DataFrame(rows)


